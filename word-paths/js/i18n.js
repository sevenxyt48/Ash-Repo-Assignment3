export function translate(language, key, values = {}) {
  const template = COPY[language]?.[key] ?? COPY.zh[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}

export function languageName(language, uiLanguage) {
  return translate(uiLanguage, `language.${language}`);
}

export function applyInterfaceLanguage(language) {
  document.documentElement.lang = LANGUAGE_TAGS[language] ?? LANGUAGE_TAGS.zh;
  for (const element of document.querySelectorAll("[data-i18n]")) {
    element.textContent = translate(language, element.dataset.i18n);
  }
  for (const element of document.querySelectorAll("[data-i18n-attr]")) {
    const [attribute, key] = element.dataset.i18nAttr.split(":");
    element.setAttribute(attribute, translate(language, key));
  }
  for (const element of document.querySelectorAll("[data-i18n-title]")) {
    element.title = translate(language, element.dataset.i18nTitle);
  }
  document.title = translate(language, "page.title");
  document.querySelector('meta[name="description"]')
    ?.setAttribute("content", translate(language, "page.description"));
}
